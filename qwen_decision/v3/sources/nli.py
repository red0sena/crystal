"""WANLI train (102,885 pairs; 20,000 sampled) as 3-way entailment / neutral / contradiction choices.

Upstream: alisawuffles/WANLI on the Hub, `train.jsonl` at a pinned commit. Licence: CC-BY-4.0.
Neither the Decision Index nor JEVal uses WANLI (the index's NLI item is ANLI test). WANLI pairs
were generated by GPT-3 from MultiNLI seed pairs, then labelled (and sometimes revised) by
crowdworkers, so it shares no construction with ANLI (the filter still checks every row; its few
drops are short generic hypotheses such as "I don't know"). ANLI train is not used: CC BY-NC.

Each question shows a premise and a hypothesis and asks how they relate. The label names, their
descriptions, the order of the options and where the hypothesis sits (state or instruction) all
vary, so the model learns the relation, not one template.
"""
from __future__ import annotations

import json
import random

from qwen_decision.v3.sources import common

NAME = "wanli-train"
REPO = "alisawuffles/WANLI"
REVISION = "61c95318fd71c55b6ba355d76253254615f387ec"
CAP = 20_000
GOLD = {"entailment": 0, "neutral": 1, "contradiction": 2}
# Option sets in (entailment, neutral, contradiction) order; descriptions are optional.
LABELS = [
    [("entailment", "if the premise is true, the hypothesis has to be true as well"),
     ("neutral", "the premise neither confirms nor rules out the hypothesis"),
     ("contradiction", "if the premise is true, the hypothesis cannot be")],
    [("implied", None), ("undetermined", None), ("contradicted", None)],
    [("true", "the first text guarantees the second"), ("unknown", "the second text may or may not hold"),
     ("false", "the first text rules the second out")],
    [("follows", "the conclusion is a safe inference"), ("not enough information", "the text leaves it open"),
     ("conflicts", "the conclusion clashes with the text")],
]
INSTRUCTIONS = [
    "Read the premise and decide how the hypothesis relates to it.",
    "Taking the first text as true, what can be said about the second one?",
    "Assuming the premise is accurate, is the hypothesis implied, ruled out, or left open?",
    "Work out the logical relationship between these two statements.",
    "Does the premise make the hypothesis true, make it false, or neither?",
]
INSTRUCTIONS_WITH_HYPOTHESIS = [
    "Assume the passage is true. Where does this statement stand?\n{h}",
    "Given only the text above, classify the following claim: {h}",
    "Suppose everything in the text is correct. Is this conclusion implied, contradicted, or undetermined?\n{h}",
]
STATE_KEYS = [("premise", "hypothesis"), ("text", "statement"), ("context", "claim")]


def build():
    path, _ = common.fetch(REPO, ["train.jsonl"], revision=REVISION)
    rows = [json.loads(line) for line in (path / "train.jsonl").open()]
    rng = random.Random(2026101601)
    rows = [rows[i] for i in sorted(rng.sample(range(len(rows)), CAP))]
    for r in rows:
        labels = rng.choice(LABELS)
        order = list(range(3))
        rng.shuffle(order)
        criteria = {labels[i][0]: labels[i][1] for i in order}
        gold = order.index(GOLD[r["gold"]])
        p, h = r["premise"], r["hypothesis"]
        if rng.random() < .3:
            state = p if rng.random() < .5 else {"text": p}
            instructions = rng.choice(INSTRUCTIONS_WITH_HYPOTHESIS).format(h=h)
        else:
            a, b = rng.choice(STATE_KEYS)
            state = {a: p, b: h} if rng.random() < .7 else f"{a.title()}: {p}\n{b.title()}: {h}"
            instructions = rng.choice(INSTRUCTIONS)
        question, target = common.choice(state, instructions, criteria, gold)
        yield common.example(NAME, str(r["id"]), "nli", state, question, target, "train")


if __name__ == "__main__":
    common.write(NAME, build(), {"upstream": REPO, "revision": REVISION, "split": "train", "licence": "CC-BY-4.0",
                                 "sampled": f"{CAP} of 102,885 (seed 2026101601)"})
