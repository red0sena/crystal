NAME_STOP = set("all the for by of to and a an in on from with api info information details detail data new my list".split())
DESC_STOP = set("api allows allow users user input output parameter parameters given specific required returns return "
                "provide provides provided based list this that with from will which".split())
DESC_LEAD = re.compile(r"^(?:this |the )?(?:api|endpoint)?\s*(?:(?:that |which )?(?:allows?|enables?|lets?|is used|used|is|for|to)\s+)*"
                       r"(?:(?:the |a )?users?\s+(?:to\s+)?)?(?:can\s+)?")


def stem(w: str) -> str:
    """Crude stem: plural s off, then the first 5 letters (vaccine / vaccination, prescribe / prescription)."""
    w = w[:-1] if len(w) > 4 and w.endswith("s") and not w.endswith("ss") else w
    return w[:5]


def name_tokens(name: str) -> list[str]:
    return [w for w in re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", name).lower().replace("_", " ").replace("-", " ").split() if w]


def verb_class(word: str, in_name: bool = False) -> str | None:
    w = word.lower()
    if in_name and w in NOMINAL:
        w = NOMINAL[w]
    if w.startswith("return"):  # "Returns a list of .." in a description; return_equipment in a name
        return ACTION["withdraw"] if in_name else "read"
    for cand in (w, w[:-1], w[:-2], w[:-3], w[:-3] + "e"):  # gets, searches, retrieving / retrieves
        if cand in ACTION:
            return ACTION[cand]
    return None


class Entry:
    """One catalog API with the word sets used to compare it with others."""

    def __init__(self, api: dict, scenario: int | None = None):
        self.api, self.name, self.scenario = api, api["apiCode"], scenario
        toks = name_tokens(self.name)
        self.norm = "".join(stem(t) for t in toks)
        self.exact = "".join(toks)
        description = str(api.get("description", ""))
        lead = DESC_LEAD.sub("", description.strip().lower(), count=1).split()
        # The operation: the first verb (or its noun: rental, cancellation) in the name, else the
        # description's leading verb ("Retrieve the list of ..."); the objects: the other name words.
        at = next((k for k, t in enumerate(toks) if verb_class(t, in_name=True)), None)
        self.op = verb_class(toks[at], in_name=True) if at is not None else (verb_class(lead[0]) if lead else None)
        self.objects = frozenset(stem(t) for k, t in enumerate(toks) if k != at and t not in NAME_STOP)
        self.desc = frozenset(stem(w) for w in content_words(description) if w not in DESC_STOP)
        self.desc_norm = " ".join(words(description))
        self.words = self.objects | self.desc


def jaccard(a: frozenset, b: frozenset) -> float:
    return len(a & b) / len(a | b) if a and b else 0.


def synonym(a: Entry, b: Entry) -> bool:
    """b may do the same job as a (as a distractor it could be a second correct answer).

    Deliberately broad, since it only decides which catalog APIs we may add: same normalized name
    or identical description; otherwise two known, different operation classes never match
    (AddReminder / DeleteReminder / QueryReminder stay as hard negatives; descriptions often differ
    only in the verb, "Add a new preference for a hospital room" / "Delete a preference ..."), and
    with the same or an unknown operation, a third of the name objects or 40% of the description
    words shared is a match: rent_equipment / equipment_rental, submit_claim / claim_reimbursement,
    get_vaccine_schedule / get_child_vaccination_schedule (words are cut to 5 letters),
    get_nearest_pharmacy / get_pharmacy_list, get_patient_info ("patient information for physical
    therapy progress") / get_progress ("progress of a patient's physical therapy sessions").
    """
    if a.norm == b.norm or (a.desc_norm and a.desc_norm == b.desc_norm):
        return True
    if a.op and b.op and a.op != b.op:
        return False
    return jaccard(a.objects, b.objects) >= 1 / 3 - 1e-9 or jaccard(a.desc, b.desc) >= .4


def duplicate(a: Entry, b: Entry) -> bool:
    """The same API twice: the same name up to case and separators, or an identical description."""
    return a.exact == b.exact or bool(a.desc_norm) and a.desc_norm == b.desc_norm


def similarity(a: Entry, b: Entry) -> float:
    return 2. * len(a.objects & b.objects) + 5. * jaccard(a.desc, b.desc) + (1. if a.scenario is not None and a.scenario == b.scenario else 0.)


def similar(a: Entry, b: Entry) -> bool:
    """b is a hard negative for a: same scenario, a shared name word, or description overlap."""
    return similarity(a, b) >= 1.


def parse_literal(text: str):
    try:
        return ast.literal_eval(text)
    except (ValueError, SyntaxError):
        return text


def parse(item: dict) -> tuple[list[dict], list[str], list[tuple[str, dict]]]:
    """Listed APIs, dialogue lines (results clipped), and (keywords, revealed API) per ToolSearcher result."""
    apis, dialogue, revealed = [], [], []
    for line in item["input"].split("\n"):
        if line.startswith('{"apiCode"'):
            apis.append(json.loads(line))
        elif line.strip() and not line.startswith("Generate API Request"):
            m = SEARCH_LINE.match(line)
            if m:
                revealed.append((m.group(1), {"apiCode": m.group(2), "description": m.group(3),
                                              "parameters": parse_literal(m.group(4)), "response": parse_literal(m.group(5))}))
            if line.startswith("API-Request:") and len(line) > RESULT_CHARS:
                line = line[:RESULT_CHARS] + " …"
            dialogue.append(line)
    return apis, dialogue, revealed


def first_user(dialogue: list[str]) -> str:
    return next((l for l in dialogue if l.startswith("User:")), "")


def step_key(dialogue: list[str]) -> tuple[str, ...]:
    """The dialogue step: the User/AI turns so far (lv1 and lv2 differ only in their API lines)."""
    return tuple(l for l in dialogue if l.startswith(("User:", "AI:")))


# ---- state layouts --------------------------------------------------------------------------------
TEXT_HEADS = ["API descriptions:", "APIs the assistant can call:", "Available APIs (one JSON object per line):"]
MD_HEADS = ["## API catalog", "## Tools", "## Callable APIs"]
CONVO_HEADS = ["Conversation:", "Dialogue so far:", "Chat history:"]


def turns(dialogue: list[str]) -> list[dict]:
    out = []
    for line in dialogue:
        role, _, text = line.partition(":")
        out.append({"role": {"API-Request": "API"}.get(role, role), "text": text.strip()})
    return out


def layout(rng: random.Random, apis: list[dict], dialogue: list[str]):
    r = rng.random()
    if r < .22:
        return {"available_apis": apis, "dialogue": dialogue}
    if r < .4:
        return {"apis": apis, "conversation": "\n".join(dialogue)}
    if r < .6:
        tools = [{"name": a["apiCode"], "description": a.get("description", ""), "input_parameters": a.get("parameters", {}),
                  "output": a.get("response", {})} for a in apis]
        return {"tools": tools, "dialogue": turns(dialogue)}
    if r < .75:
        lines = [rng.choice(MD_HEADS)]
        for a in apis:
            lines += ["", f"### {a['apiCode']}", f"Description: {a.get('description', '')}",
                      f"Parameters: {json.dumps(a.get('parameters', {}), ensure_ascii=False)}",
                      f"Returns: {json.dumps(a.get('response', {}), ensure_ascii=False)}"]
        return {"conversation": turns(dialogue), "catalog": "\n".join(lines)}
    head, convo = rng.choice(TEXT_HEADS), rng.choice(CONVO_HEADS)
    catalog = [head, *(json.dumps(a, ensure_ascii=False) for a in apis)]
    talk = [convo, *dialogue]
    parts = [catalog, talk] if r < .9 else [talk, catalog]
    return "\n".join(parts[0] + [""] + parts[1])


def tool_list(state) -> list[tuple[str, str, object]]:
    """(name, description, parameters) of every API in a state's tool list, parsed back from the layout."""
    if isinstance(state, dict) and "catalog" in state:
        out, cur = [], None
        for line in state["catalog"].split("\n"):
            if line.startswith("### "):
                cur = [line[4:], None, None]
                out.append(cur)
            elif cur and line.startswith("Description: "):
                cur[1] = line[len("Description: "):]
            elif cur and line.startswith("Parameters: "):
                cur[2] = json.loads(line[len("Parameters: "):])
        return [tuple(t) for t in out]
    if isinstance(state, dict):
        key = next(k for k in ("available_apis", "apis", "tools") if k in state)
        return [(t.get("apiCode", t.get("name")), t.get("description"), t.get("parameters", t.get("input_parameters")))
                for t in state[key]]
    lines = state.split("\n")
    start = next(i for i, l in enumerate(lines) if l in TEXT_HEADS) + 1
    out = []
    for line in lines[start:]:
        if not line:
            break
        t = json.loads(line)
        out.append((t["apiCode"], t.get("description"), t.get("parameters")))
    return out


# ---- build ----------------------------------------------------------------------------------------
def build(stats: dict):
    local, _ = common.fetch(REPO, list(FILES.values()) + ["README.md"], revision=REVISION)
    items = {level: json.loads((local / path).read_text()) for level, path in FILES.items()}
    parsed = {level: [parse(it) for it in rows] for level, rows in items.items()}
    flt = Filter(common.DECONTAM)

    def clean(api: dict) -> bool:
        for t in strings(api):
            if short_keys(t) & flt.short:
                return False
            h = shingles(words(t))
            if len(h):
                at = np.minimum(np.searchsorted(flt.table, h), len(flt.table) - 1)
                if (flt.table[at] == h).any():
                    return False
        return True

    # Catalog: every distinct (name, description) definition of lv1, plus ToolSearcher.
    catalog, seen = [], set()
    for s, (apis, _, _) in enumerate(parsed["lv1"]):
        for api in apis:
            key = (api["apiCode"], api.get("description", ""))
            if key not in seen:
                seen.add(key)
                catalog.append(Entry(api, s))
    searcher_api = parsed["lv2"][0][0][0]
    assert searcher_api["apiCode"] == SEARCHER
    searcher = Entry(searcher_api)
    stats["catalog_definitions"] = len(catalog)
    stats["catalog_names"] = len({e.name for e in catalog})
    pool = [e for e in catalog if clean(e.api)]
    stats["catalog_screened_out_contamination"] = len(catalog) - len(pool)
    by_scenario: dict[int, list[Entry]] = {}
    for e in pool:
        by_scenario.setdefault(e.scenario, []).append(e)
    scenarios = sorted(by_scenario)

    # Nearest neighbours of every pool entry (for decoy clusters), through an inverted word index.
    inverted: dict[str, list[int]] = {}
    for j, e in enumerate(pool):
        for w in e.words:
            inverted.setdefault(w, []).append(j)
    neighbours = []
    for j, e in enumerate(pool):
        cands = {k for w in e.words for k in inverted[w] if k != j}
        scored = sorted(((similarity(e, pool[k]), k) for k in cands), key=lambda x: (-x[0], x[1]))
        neighbours.append([k for s, k in scored[:NEIGHBOURS] if s >= 1.])

    pkey = {(e.name, e.api.get("description", "")): j for j, e in enumerate(pool)}

    def near(e: Entry) -> list[int]:
        """Pool indices of e's nearest neighbours, most similar first."""
        j = pkey.get((e.name, e.api.get("description", "")))
        if j is not None and pool[j].scenario == e.scenario:
            return neighbours[j]
        cands = {k for w in e.words for k in inverted.get(w, ())}
        scored = sorted(((similarity(e, pool[k]), k) for k in cands), key=lambda x: (-x[0], x[1]))
        return [k for sc, k in scored[:NEIGHBOURS] if sc >= 1.]

    # What each step's annotations call, across levels; which lv1 scenarios share a dialogue's opening.
    step_calls: dict[tuple, set[str]] = {}
    origin: dict[str, set[int]] = {}
    found = {}
    definitions: dict[str, dict[str, dict]] = {}  # name -> description -> definition, lv1 listed + lv2 revealed
    for e in catalog:
        definitions.setdefault(e.name, {})[e.api.get("description", "")] = e.api
    for level, rows in items.items():
        for i, item in enumerate(rows):
            _, dialogue, revealed = parsed[level][i]
            step_calls.setdefault(step_key(dialogue), set()).add(GOLD.match(item["output"].strip()).group(1))
            if level == "lv1":
                origin.setdefault(first_user(dialogue), set()).add(i)
            for kw, api in revealed:
                found.setdefault((first_user(dialogue), kw), api)
                definitions.setdefault(api["apiCode"], {})[api["description"]] = api
    stats["steps_with_differing_golds"] = sum(len(v) > 1 for v in step_calls.values())

    blocked = toolret_turns()
    rng = random.Random(3)
    ex = stats["excluded_candidates"]
    for level, rows in items.items():
        for i, item in enumerate(rows):
            apis, dialogue, revealed = parsed[level][i]
            output = item["output"].strip()
            gold = GOLD.match(output).group(1)
            listed = {a["apiCode"]: a for a in apis}
            for _, api in revealed:
                listed.setdefault(api["apiCode"], api)
            if gold not in listed:
                stats["skipped"]["gold_not_offered"] += 1
                continue
            if any(" ".join(words(line.split(":", 1)[1])) in blocked for line in dialogue if line.startswith("User:")):
                stats["skipped"]["toolret_exact"] += 1
                continue
            scenario = i if level == "lv1" else None
            base = [Entry(a, scenario) for a in listed.values()]
            gold_entry = next(e for e in base if e.name == gold)
            # (1) what other upstream rows call at this same step
            other_calls = step_calls[step_key(dialogue)] - {gold, SEARCHER}
            other_entries = [Entry(d) for name in sorted(other_calls) for d in definitions.get(name, {}).values()]
            if any(e.name in other_calls for e in base):
                stats["skipped"]["offered_api_called_by_other_annotation"] += 1
                continue
            if gold == SEARCHER:
                m = KEYWORDS.search(output)
                kw = m.group(1) if m else ""
                nxt = found.get((first_user(dialogue), kw))
                stats["searcher_gold_next_api_known"][str(nxt is not None).lower()] += 1
                kw_text = kw.strip("'\"")
                kw_words = frozenset(stem(w) for w in content_words(kw_text))
                kw_op = verb_class(kw_text.split()[0]) if kw_text.split() else None
                refs = [Entry(nxt)] if nxt else []
                pseudo = Entry({"apiCode": "_".join(sorted(kw_words)) or "search", "description": kw_text})
                ref = refs[0] if refs else pseudo
                same_origin = {a["apiCode"] for s in origin.get(first_user(dialogue), ()) for a in parsed["lv1"][s][0]}

                def why(e: Entry, offered: bool = False) -> str | None:
                    if e.name in other_calls or any(synonym(o, e) for o in other_entries):
                        return "same_step_other_annotation"
                    if any(synonym(r, e) for r in refs):
                        return "near_synonym"
                    if e.name in same_origin and not offered:  # upstream offered it and still searched
                        return "same_dialogue_scenario_api"
                    if (kw_words and len(kw_words & e.words) / len(kw_words) >= .6
                            and not (kw_op and e.op and kw_op != e.op)):
                        return "covers_search_keywords"
                    return None

                reasons = [r for r in (why(e, offered=True) for e in base if e.name != SEARCHER) if r]
                if reasons:
                    stats["skipped"][f"offered_api_already_answers_search:{reasons[0]}"] += 1
                    continue
            else:
                ref = gold_entry

                def why(e: Entry) -> str | None:
                    if e.name in other_calls or any(synonym(o, e) for o in other_entries):
                        return "same_step_other_annotation"
                    if synonym(ref, e):
                        return "near_synonym"
                    return None

                # Upstream's own list is trusted unless it holds an exact duplicate (name or description).
                if any(e.name != gold and e.name != SEARCHER and duplicate(ref, e) for e in base):
                    stats["skipped"]["offered_duplicate_of_gold"] += 1
                    continue

            taken = {e.norm for e in base} | {e.name for e in base}
            mode = "catalog" if rng.random() < .35 else "subset"
            with_searcher = level == "lv2" or mode == "catalog" or rng.random() < .5
            if with_searcher and SEARCHER not in listed:
                base.append(searcher)
                taken |= {searcher.norm, searcher.name}
            chosen = list(base)
            rejected: dict[int, str | None] = {}

            def ok(e: Entry) -> bool:
                if e.name in taken or e.norm in taken:
                    return False
                if id(e) not in rejected:
                    rejected[id(e)] = why(e)
                    if rejected[id(e)]:
                        ex[rejected[id(e)]] += 1
                return rejected[id(e)] is None

            def add(e: Entry) -> None:
                chosen.append(e)
                taken.update((e.name, e.norm))

            lo, hi = SUBSET if mode == "subset" else CATALOG
            size = max(rng.randint(lo, hi), len(base) + 3)

            def hard_size() -> int:
                return rng.randint(3, 8) if mode == "subset" else rng.randint(8, 20)

            def grow(members: list[Entry], n: int, must: Entry | None = None) -> int:
                """Add up to n acceptable catalog APIs closest to the members as a group (summed
                similarity, so no single member is the centre); with `must`, only APIs similar to it."""
                score: Counter = Counter()
                for m in members:
                    for j in near(m):
                        score[j] += similarity(m, pool[j])
                added = 0
                for j, _ in sorted(score.items(), key=lambda x: (-x[1], x[0])):
                    if added >= n or len(chosen) >= size:
                        break
                    if (must is None or similar(must, pool[j])) and ok(pool[j]):
                        add(pool[j])
                        added += 1
                return added

            # Hard negatives: catalog APIs similar to the gold (or to the API a search looks for), ranked
            # by closeness to the gold and its listed companions together.
            companions = [m for m in base if m.name not in (gold, SEARCHER)]
            n_hard = grow([ref] + companions, hard_size(), must=ref)
            gold_cluster = n_hard + len(companions) + (gold != SEARCHER)
            # Decoy clusters: other scenarios with their own nearest APIs, sized like the gold's cluster,
            # while the budget lasts; so the gold's cluster is not the only tight group in the list.
            avoid = {scenario} | origin.get(first_user(dialogue), set())
            decoys = tries = 0
            while size - len(chosen) >= max(2, gold_cluster // 2) and tries < 40:
                tries += 1
                s = scenarios[rng.randrange(len(scenarios))]
                if s in avoid:
                    continue
                avoid.add(s)
                members = [e for e in by_scenario[s] if ok(e)][:min(max(1, len(companions) + 1), size - len(chosen))]
                if not members:
                    continue
                for e in members:
                    add(e)
                grow(members, max(0, gold_cluster - len(members) + rng.randint(-1, 1)))
                decoys += 1
            # Random fill from the whole (screened) catalog.
            tries = 0
            while len(chosen) < size and tries < 4000:
                tries += 1
                e = pool[rng.randrange(len(pool))]
                if ok(e):
                    add(e)
            names = [e.name for e in chosen]
            assert len(set(names)) == len(names), (level, i)
            tools = [e.api for e in chosen]
            rng.shuffle(tools)
            shown = dialogue
            if level == "lv2" and gold != SEARCHER and rng.random() < .4:
                shown = [l for l in dialogue if not l.startswith("API-Request: [ToolSearcher(")]
                stats["lv2_search_lines_dropped"] += 1
            state = layout(rng, tools, shown)
            order = list(names)
            rng.shuffle(order)
            if rng.random() < .3:
                options = {f"option_{k}": n for k, n in enumerate(order)}
            else:
                options = order
            question, target = common.choice(state, common.instruction(rng, PHRASINGS), options, order.index(gold))
            # Exact check: the tool list parsed back from the state holds exactly the options, each defined.
            parsed_tools = tool_list(state)
            assert sorted(t[0] for t in parsed_tools) == sorted(order), (level, i)
            assert all(t[1] is not None and t[2] is not None for t in parsed_tools), (level, i)
            group = f"{level}:{mode}"
            why_flagged = flt.flagged(strings(state) + strings(question["instructions"]), options=strings(question["criteria"]))
            if why_flagged:  # write() drops it; record where the matching text sits
                kind = "short_text" if why_flagged.startswith("short") else "shingles"
                where = "tool_list" if flt.flagged(strings(tools)) else "dialogue" if flt.flagged(strings(shown)) else "combined"
                stats["filter_breakdown"][f"{kind}:{where}"] += 1
                stats["filter_breakdown"]["documents_mode_would_still_drop"] += bool(flt.flagged(
                    strings(state) + strings(question["instructions"]), documents=True, options=strings(question["criteria"])))
            stats["options"][group].append(len(order))
            stats["hard_negatives"][group].append(n_hard)
            stats["hard_negatives_below_3"][f"{group}:{'search' if gold == SEARCHER else 'api'}"] += n_hard < 3
            stats["decoy_clusters"][group].append(decoys)
            stats["rows_with_similar_distractor"][group] += any(e.name != gold and similar(ref, e) for e in chosen)
            # Shortcut probe: is the gold the option most similar to all the others?
            cent = {e.name: sum(similarity(e, o) for o in chosen if o is not e) for e in chosen}
            stats["gold_is_cluster_centre"][group] += max(cent, key=cent.get) == gold
            yield common.example(NAME, f"{level}:{i}", "tool-call", state, question, target, "train")


