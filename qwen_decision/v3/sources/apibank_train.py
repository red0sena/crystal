"""API-Bank training data as "which API should be called next?" choices over a listed API catalog.

Upstream: liminghao1630/API-Bank `training-data/` (MIT), pinned revision; only the training split
(the repo's `test-data/` and the DAMO-ConvAI `lv1-lv2-samples` are the evaluation side and are not
read). The index scores the `lv1-lv2-samples` test dialogues (53-API catalog); the training data was
generated separately over a different, much larger API pool. ToolRet's `apibank` queries (101) are
dropped by exact normalized user-turn match here and by the contamination filter.

  - lv1-api-train.json (3,178): 2-4 API descriptions of one scenario are listed; the gold is the
    API in the target `API-Request: [Name(..)]`.
  - lv2-api-train.json (6,291): only ToolSearcher is listed; earlier ToolSearcher results in the
    dialogue reveal further APIs (one per result, as "API: name | Description: .. | Input
    parameters: .. | Output result: .."). The gold is either a new search or a revealed API.
Rows whose gold API is neither listed nor revealed are skipped (upstream noise).

Label origin. The gold is derived programmatically: it is the API name parsed from the upstream
`output` field ("API-Request: [Name(...)]"). That call was not written by people. The API-Bank
paper (Li et al., EMNLP 2023, arXiv:2304.08244, sec. "Training set" / Multi-agent) states the
training set (1,888 dialogues, 2,138 APIs, 1,000 domains) was generated by five ChatGPT agents
(domains -> APIs -> query -> API calls and responses -> a tester agent that discards ~35%),
"eliminat[ing] the need for human labelers"; "the training data is generated automatically by the
LLM, while the evaluation data is manually annotated" (314 dialogues). A human audit of 100 training
samples found 94% usable. The repo README describes the same split (evaluation: "We annotate 314
tool-use dialogues"; training: "Multi-agent Dataset Synthesis"). So the labels are LLM-generated
API-call annotations, about 6% noisy; which other APIs are wrong is decided by this builder (below).

State. Every option is an API whose name and full definition (description, parameters, response, as
upstream gives them) are in the state's tool list, and the tool list holds exactly the options, in
an order shuffled independently of the option order. Each row is checked by parsing the tool list
back out of the rendered state (tool_list()) and asserting set equality with the option names.
(The original version added distractor names without definitions, so 85% of options were absent
from the state and the gold was often the only listed name: "pick the name that appears in the
input" answered it.)

Catalog. Every distinct (name, description) definition in lv1 (1,767 names, 2,628 definitions;
generated scenarios reuse names such as cancel_appointment with different meanings) plus
ToolSearcher. Definitions with any text touching the contamination index (a short-text key or a
single kept shingle; e.g. the parameter description "The name of the building.") are not used as
distractors, so a mix of distractors never trips the filter (the row's own scenario APIs are kept
and checked by write()).

Options for a row = the APIs upstream offers it (lv1 scenario; lv2 ToolSearcher + revealed APIs)
+ hard negatives + decoy clusters + random fill:
  - hard negatives: catalog APIs similar to the gold (a shared name word or description words,
    words cut to 5 letters), ranked by closeness to the gold and its listed companions together;
    e.g. AddReminder gets DeleteReminder / QueryReminder. For a ToolSearcher gold the reference is
    the API that search goes on to reveal later in the same dialogue (or, when there is none, the
    search keywords), so same-domain APIs are listed while searching stays right.
  - decoy clusters: other lv1 scenarios with their own nearest APIs, sized like the gold's cluster,
    while the budget lasts. Without them the gold is the centre of the only tight cluster in the
    list (15% of rows in the unfinished rebuild, 3x chance), a shortcut the index's fixed catalog does
    not reward; the manifest's gold_is_cluster_centre is that probe (vs cluster_centre_chance).
  - sizes: "subset" rows (65%) have 8-30 options and 3-8 hard negatives (all there are when fewer);
    "catalog" rows (35%) have 40-64 options, the size of the index's published catalog (53), with
    8-20 hard negatives and always ToolSearcher. The whole upstream catalog (1,767 names, ~600k
    tokens) is over the 255-option limit and cannot be one question, so the large catalog is a
    sample of it.
  - ToolSearcher is on every lv2 list and on half the lv1 subset lists (the gold is listed there,
    so calling it directly beats searching, as in API-Bank level 1 and the index's catalog).

No second correct answer (checked per candidate; counts in the manifest's excluded_candidates and
skipped):
  1. same step, other annotation: 2,063 dialogue steps (same User/AI turns) occur in both lv1 and
     lv2 with different golds (lv1 lists the API and calls it; lv2 lists only ToolSearcher and
     searches). Every API other than ToolSearcher that any upstream row calls at the same step is
     excluded from the other rows of that step (all definitions of that name and their
     near-synonyms); a row whose upstream-offered list holds such an API is dropped.
  2. near-synonyms (synonym()) of the gold, or of the API a ToolSearcher gold is looking for. The
     test is deliberately broad, since it only removes APIs we would add: same normalized name or
     identical description; else the operation class (read incl. compute/recommend; make; delete;
     update; from the name's verb or its noun, else the description's leading verb) must not
     differ, and a third of the name objects or 40% of the description words shared is a match.
     So AddReminder / DeleteReminder / QueryReminder stay hard negatives while rent_equipment /
     equipment_rental or get_vaccine_schedule / get_child_vaccination_schedule never meet.
  3. ToolSearcher gold: also excluded are the APIs of the lv1 scenario that generated the same
     dialogue (same first user turn) and APIs covering >= 60% of the search keywords (unless their
     operation differs from the keywords' verb); a row whose upstream-offered APIs (revealed
     earlier) already answer the search need by rules 1-3 is dropped (upstream noise).
  4. upstream's own lists are trusted (the tester agent checked them; a heuristic flags e.g.
     search_trials / get_trial_info), except exact duplicates of the gold (same name up to case and
     separators, or identical description): such rows are dropped.
lv2 rows whose gold is a revealed API drop the ToolSearcher lines from the dialogue 40% of the time
(the revealed API is then found only in the catalog, as in lv1), so "the API named in the dialogue"
is not a shortcut either. API-Request results in the dialogue are clipped to 600 characters.
Option keys are the API names (70%) or option_<i> keys whose value is the API name (30%).

Contamination: strict filter (common.write). Drops are the row's own scenario/dialogue texts
(distractors are pre-screened); their breakdown is in the manifest (filter_breakdown).
"""
